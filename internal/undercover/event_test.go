// fakeGitHub answers GETs from a path->JSON map and records every PATCH.
type fakeGitHub struct {
	get     map[string]string
	patches map[string]string
}

func (f *fakeGitHub) Get(_ context.Context, path string) ([]byte, error) {
	if body, ok := f.get[path]; ok {
		return []byte(body), nil
	}
	if strings.Contains(path, "/comments?") || strings.Contains(path, "/commits?") {
		return []byte("[]"), nil
	}
	return nil, fmt.Errorf("unexpected GET %s", path)
}

func (f *fakeGitHub) Patch(_ context.Context, path string, fields map[string]string) error {
	if f.patches == nil {
		f.patches = map[string]string{}
	}
	f.patches[path] = fields["body"]
	return nil
}

func prJSON(title, body string) string {
	b, _ := json.Marshal(map[string]string{"title": title, "body": body})
	return string(b)
}

func commentsJSON(bodies map[int]string) string {
	var list []map[string]any
	for id, body := range bodies {
		list = append(list, map[string]any{"id": id, "body": body})
	}
	b, _ := json.Marshal(list)
	return string(b)
}

const (
	prPath       = "/repos/o/r/pulls/7"
	issueComPath = "/repos/o/r/issues/7/comments?per_page=100&page=1"
	reviewPath   = "/repos/o/r/pulls/7/comments?per_page=100&page=1"
	footer       = "\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nhttps://claude.ai/code/session_01"
)

var triggers = map[string]string{
	"pull_request":                `{"action":"edited","repository":{"full_name":"o/r"},"pull_request":{"number":7}}`,
	"issue_comment":               `{"action":"created","repository":{"full_name":"o/r"},"issue":{"number":7,"pull_request":{"url":"x"}},"comment":{"id":11}}`,
	"pull_request_review_comment": `{"action":"created","repository":{"full_name":"o/r"},"pull_request":{"number":7},"comment":{"id":21}}`,
}

// Every trigger reads the same three places on the PR: title and body, the
// issue comments and the review comments.
func TestCheckEvent_EveryTriggerStripsATrailingFooterEverywhereOnThePR(t *testing.T) {
	t.Parallel()
	for name, event := range triggers {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			gh := &fakeGitHub{get: map[string]string{
				prPath:       prJSON("Fix the timer", "Fixes the retry timer."+footer),
				issueComPath: commentsJSON(map[int]string{11: "Looks right." + footer, 12: "Plain comment."}),
				reviewPath:   commentsJSON(map[int]string{21: "Nit: rename this.\n\n_Generated by [Claude Code](https://x.example)_"}),
			}}
			res, err := CheckEvent(context.Background(), []byte(event), New(nil), gh)
			if err != nil {
				t.Fatal(err)
			}
			if len(res.Failures) != 0 {
				t.Fatalf("a strippable footer failed the check: %q", res.Failures)
			}
			want := map[string]string{
				prPath:                          "Fixes the retry timer.",
				"/repos/o/r/issues/comments/11": "Looks right.",
				"/repos/o/r/pulls/comments/21":  "Nit: rename this.",
			}
			if len(gh.patches) != len(want) {
				t.Errorf("patches = %q, want %q", gh.patches, want)
			}
			for path, body := range want {
				if gh.patches[path] != body {
					t.Errorf("PATCH %s body = %q, want %q", path, gh.patches[path], body)
				}
			}
			if len(res.Stripped) != 3 {
				t.Errorf("stripped = %q, want one line per edited text", res.Stripped)
			}
		})
	}
}

func TestCheckEvent_AMidProseHitFailsWithoutAnEdit(t *testing.T) {
	t.Parallel()
	gh := &fakeGitHub{get: map[string]string{
		prPath:       prJSON("Fix the timer", "Claude wrote most of this.\n\nFixes the timer."+footer),
		issueComPath: commentsJSON(map[int]string{11: "ran under opus-5, looks fine"}),
	}}
	res, err := CheckEvent(context.Background(), []byte(triggers["pull_request"]), New(nil), gh)
	if err != nil {
		t.Fatal(err)
	}
	if len(gh.patches) != 0 {
		t.Errorf("a mid-prose hit was edited: %q", gh.patches)
	}
	joined := strings.Join(res.Failures, "\n")
	for _, want := range []string{"PR body", "Claude wrote most of this.", "issue comment 11", "ran under opus-5, looks fine"} {
		if !strings.Contains(joined, want) {
			t.Errorf("failures %q lack %q", joined, want)
		}
	}
}

