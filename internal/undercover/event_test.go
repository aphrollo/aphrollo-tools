// endlessGitHub answers every comment page full, the shape of a thread that
// never ends; the check still stops.
type endlessGitHub struct{ commentGets int }

func (e *endlessGitHub) Get(_ context.Context, path string) ([]byte, error) {
	if strings.HasPrefix(path, "/repos/o/r/issues/9/comments?") {
		e.commentGets++
		full := map[int]string{}
		for id := 1; id <= 100; id++ {
			full[id] = "ok"
		}
		return []byte(commentsJSON(full)), nil
	}
	return nil, fmt.Errorf("unexpected GET %s", path)
}

func (e *endlessGitHub) Patch(context.Context, string, map[string]string) error { return nil }

func TestCheckEvent_StopsAfterThePageCap(t *testing.T) {
	t.Parallel()
	gh := &endlessGitHub{}
	event := `{"repository":{"full_name":"o/r"},"issue":{"number":9},"comment":{"id":1}}`
	if _, err := CheckEvent(context.Background(), []byte(event), New(nil), gh); err != nil {
		t.Fatal(err)
	}
	if gh.commentGets != 30 {
		t.Errorf("read %d comment pages, want the cap of 30", gh.commentGets)
	}
}

func commitsJSON(commits ...[4]string) string {
	var list []map[string]any
	for _, c := range commits {
		an, ae, _ := strings.Cut(c[1], "|")
		cn, ce, _ := strings.Cut(c[2], "|")
		list = append(list, map[string]any{"sha": c[0], "commit": map[string]any{
			"author":    map[string]string{"name": an, "email": ae},
			"committer": map[string]string{"name": cn, "email": ce},
			"message":   c[3],
		}})
	}
	b, _ := json.Marshal(list)
	return string(b)
}

const prCommitsPath = "/repos/o/r/pulls/7/commits?per_page=100&page=1"

// A squash merge lists every commit author as a co-author, so a PR whose
// commits carry a tell leaks it into main however clean its text is.
func TestCheckEvent_FailsAPRCommitWhoseIdentityOrTrailerCarriesATell(t *testing.T) {
	t.Parallel()
	person, web := "Jane Doe|jane@example.com", "GitHub|noreply@github.com"
	for _, c := range []struct {
		commit [4]string
		field  string
	}{
		{[4]string{"aaaaaaaaaaaaaaaa", "Claude|noreply@anthropic.com", web, "Fix it"}, "author"},
		{[4]string{"bbbbbbbbbbbbbbbb", person, "Claude|noreply@anthropic.com", "Fix it"}, "committer"},
		{[4]string{"cccccccccccccccc", person, web, "Fix it\n\nCo-authored-by: Claude <noreply@anthropic.com>"}, "Co-authored-by trailer"},
	} {
		gh := &fakeGitHub{get: map[string]string{
			prPath:        prJSON("Fix the timer", "Fixes it."),
			prCommitsPath: commitsJSON([4]string{"0000000000000000", person, web, "Earlier work"}, c.commit),
		}}
		res, err := CheckEvent(context.Background(), []byte(triggers["pull_request"]), New(nil), gh)
		if err != nil {
			t.Fatal(err)
		}
		joined := strings.Join(res.Failures, "\n")
		for _, want := range []string{c.commit[0][:12], c.field, "noreply@anthropic.com"} {
			if !strings.Contains(joined, want) {
				t.Errorf("%s: failures %q lack %q", c.field, joined, want)
			}
		}
		if len(gh.patches) != 0 {
			t.Errorf("%s: a commit finding edited text: %q", c.field, gh.patches)
		}
	}
}

