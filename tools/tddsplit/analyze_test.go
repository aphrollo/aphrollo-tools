// writeTree writes files (slash paths relative to dir) under dir.
func writeTree(t *testing.T, dir string, files map[string]string) {
	t.Helper()
	for name, body := range files {
		p := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

// aliasFixture is one unsplit package p: a.go holds a constant, a seam var a
// test in its own file reassigns, a read-only var, a type with an unexported
// field and a variadic func; b.go uses all of them, and reads the field.
var aliasFixture = map[string]string{
	"go.mod": "module example.com/fx\n\ngo 1.26\n",
	"p/a.go": `package p

import "strings"

const limit = 3

var hook = func(n int) bool { return n > limit }

var names = []string{"a"}

type thing struct{ name string }

func helper(s string, rest ...string) (string, error) { return s + strings.Join(rest, ""), nil }
`,
	"p/a_test.go": `package p

import "testing"

func TestHook_StubIsSeen(t *testing.T) {
	old := hook
	hook = func(int) bool { return true }
	defer func() { hook = old }()
	if !hook(0) {
		t.Fatal("stub not seen")
	}
}
`,
	"p/b.go": `package p

func Use() bool {
	t := thing{name: "x"}
	_, _ = helper(t.name)
	_ = names
	return hook(limit)
}
`,
}

const aliasManifest = `root p
[packages]
low L0 p/low
p   L1 p
[files]
a.go      low
a_test.go low
b.go      p
`

func analyzeFixture(t *testing.T, files map[string]string, manifest, levels string) *Analysis {
	t.Helper()
	repo := t.TempDir()
	writeTree(t, repo, files)
	m, err := ParseManifest(strings.NewReader(manifest))
	if err != nil {
		t.Fatal(err)
	}
	lv, err := ParseLevels(levels)
	if err != nil {
		t.Fatal(err)
	}
	a, err := Analyze(repo, m, lv)
	if err != nil {
		t.Fatal(err)
	}
	return a
}

func TestAnalyze_ConsumerAliasesFollowTheKindRules(t *testing.T) {
	a := analyzeFixture(t, aliasFixture, aliasManifest, "L0")
	deps := string(a.Generated["p/api_low.go"])
	for _, want := range []string{
		"// Code generated by tddsplit. DO NOT EDIT.",
		"const limit = low.Limit",
		"func hook(p0 int) bool { return low.Hook(p0) }",
		"var names = low.Names",
		"type thing = low.Thing",
		"func helper(p0 string, p1 ...string) (string, error) { return low.Helper(p0, p1...) }",
	} {
		if !strings.Contains(deps, want) {
			t.Errorf("p/api_low.go lacks %q:\n%s", want, deps)
		}
	}
	if strings.Contains(deps, "var hook") {
		t.Errorf("the seam hook is copied as a var, so a stub assigned in low never reaches p:\n%s", deps)
	}
}

